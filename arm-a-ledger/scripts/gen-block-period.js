// Block-period sensitivity cells (design Section 6: 1 s and 5 s; primary 2 s). Writes, next to the generated network,
//   genesis-bp<N>.json   = the generated genesis.json with only qbft.blockperiodseconds changed (same validators,
//                          same keys, same accounts),
//   bp<N>.override.yml   = a compose override that mounts that genesis into the 4 validators.
// The primary network files are not changed. Usage (repo root): node arm-a-ledger/scripts/gen-block-period.js 1 5
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(resolve(fileURLToPath(new URL('..', import.meta.url))), 'network', 'generated');
const base = JSON.parse(readFileSync(join(dir, 'genesis.json'), 'utf8'));
for (const arg of process.argv.slice(2)) {
  const n = Number(arg);
  if (!Number.isInteger(n) || n < 1) throw new Error(`block period must be a whole number of seconds: ${arg}`);
  const g = structuredClone(base);
  if (!g.config?.qbft) throw new Error('genesis.json has no config.qbft section');
  g.config.qbft.blockperiodseconds = n;
  writeFileSync(join(dir, `genesis-bp${n}.json`), JSON.stringify(g, null, 2));
  const svc = (i) => `  besu${i}:\n    volumes:\n      - ./genesis-bp${n}.json:/config/genesis.json:ro\n      - ./node${i}/key:/config/key:ro\n`;
  writeFileSync(join(dir, `bp${n}.override.yml`),
    `# Generated by scripts/gen-block-period.js: block period ${n} s (sensitivity cell); only the genesis file differs.\nservices:\n${[1, 2, 3, 4].map(svc).join('')}`);
  console.log(`wrote genesis-bp${n}.json and bp${n}.override.yml (blockperiodseconds ${n})`);
}
